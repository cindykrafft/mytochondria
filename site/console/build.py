def r2_issue(path):
    s=read(path); m=re.search(r"^Title:\s*(.+)$", s, re.M); t=m.group(1).strip()
    body=foot(strip_comment(s[m.end():]))
    cm=re.search(r"[\(\[]\s*comment (?:on|for) (#\d+(?:\s*/\s*#\d+)*)\s*[\)\]]", t, re.I)
    existing=None
    if cm:
        existing=int(re.search(r"#(\d+)", cm.group(1)).group(1))
        t=(t[:cm.start()]+t[cm.end():]).strip().rstrip(" :—")
    return t, body, existing
def r2_prs(path):
    s=read(path); out=[]
    for m in re.finditer(r'^### PR (\d+) — `([^`]+)` — "(.+?)"\s*\n(.*?)(?=^### PR |\Z)', s, re.S|re.M):
        out.append(dict(n=int(m.group(1)), branch=m.group(2), title=m.group(3).strip(), body=foot(m.group(4).strip())))
    return out
